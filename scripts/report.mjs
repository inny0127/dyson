// Runs model v4 and writes NUMBERS.md: the figures the page shows, per hardware era, plus the
// sweeps behind the design choices. Usage: node scripts/report.mjs [out.md]
import { writeFileSync } from 'node:fs';
import * as h from '../src/model/hybrid.js';
import { MERCURY, EARTH } from '../src/model/constants.js';
import { sci, pct, kg } from '../src/util/format.js';

const out = process.argv[2] || 'NUMBERS.md';
const L = [];
const w = (...a) => L.push(a.join(''));
const table = (head, rows) => {
  w('| ', head.join(' | '), ' |');
  w('|', head.map(() => '---').join('|'), '|');
  for (const r of rows) w('| ', r.join(' | '), ' |');
  w('');
};
const yr = (p, t) => (Number.isFinite(t) ? String(Math.round(p.seedYear + t)) : 'never');
const gW = x => `${(x * 1e3).toFixed(2)} g/W`;

w('# The numbers');
w('');
w('Generated by `node scripts/report.mjs` from `src/model/hybrid.js` (model v4). The page computes the same numbers with the same code.');
w('"Mature" eras are the hardware the bulk of the swarm is built with (after ~2095); see `docs/future-tech.md`.');
w('Hardware rows are for sails on their thermal orbits inside Earth\'s (the shell), with each era\'s film (thinned to 0.52 of the design spec in the mature eras). Build and Earth rows are for the default: the closed swarm, the Sun enclosed at 0.95 AU with a film thinned to 0.52 (2026 hardware keeps the full film), a mirror cap at 0.98 AU round the Sun–Earth line with a window for Earth, Mercury\'s rock and then its core, and each era\'s service life (`docs/closed-swarm.md`).');
w('');

w('## Hardware eras at a glance');
w('');
const eras = ['2026', 'low', 'mid', 'high'];
const rows = [];
const ds = {};
for (const e of eras) {
  const p = h.eraParams(e);
  const d = h.compute(p);
  const s = h.swarmAt({ ...p, earthPlacement: 'shell' }, 0.01);
  const far = { ...p, earthPlacement: 'farside', spillInside: 'stop', farsideLat: 60 };
  const uni = { ...p, earthPlacement: 'uniform' };
  ds[e] = { p, d, s, E: h.earthLimits(p, d), F: h.earthLimits(far, h.compute(far)), U: h.earthLimits(uni, h.compute(uni)) };
}
const line = (label, f) => rows.push([label, ...eras.map(e => f(ds[e]))]);
line('Sail orbit at 1 % coverage', ({ s }) => `${s.rSail.toFixed(3)} AU`);
line('Film / chip temperature', ({ s, p }) => `${Math.round(s.sail.T)} / ${Math.round(s.sail.T + p.filmSpreadDT)} K`);
line('Chiplet pitch', ({ s }) => `${(s.sail.chipPitch * 1e3).toFixed(1)} mm`);
line('Chip power per 279 m sail', ({ s, p }) => `${(s.sail.chipWm2 * p.sailArea / 1e6).toFixed(1)} MW`);
line('Sail mass per W', ({ s }) => gW(s.sail.kgPerW));
line('Pod mass per W', ({ s }) => gW(s.pod.kgPerW));
line('Pod share of chip power', ({ s }) => pct(s.q, 1));
line('Swarm mass per W', ({ s }) => gW(s.kgPerW));
line('Swarm mass per W, closed (0.95 AU, thin film)', ({ p }) => gW(h.swarmAt(p, 0.01).kgPerW));
line('Service life / recycled', ({ p }) => `${p.serviceLife} yr / ${pct(p.recycleFrac, p.recycleFrac > 0.99 ? 2 : 0)}`);
line('Energy per op (sail)', ({ s }) => `${sci(s.sail.jPerFlop, 2)} J`);
line('FLOP per joule of sunlight', ({ s }) => sci(s.flops / s.intercepted, 2));
line('Industry doubling (with fabs)', ({ d }) => `${d.growth.doublingYearsEff.toFixed(2)} yr`);
line('Heat wall', ({ p, d }) => yr(p, d.growth.tCap));
line('1 % of sunlight', ({ p, d }) => yr(p, d.yearsToCoverage(0.01)));
line('10 % of sunlight', ({ p, d }) => yr(p, d.yearsToCoverage(0.1)));
line('Ceiling (refresh or rock, industry left alone)', ({ d }) => pct(d.reachableCoverage, 1));
line('Computing at the ceiling', ({ p, d }) => `${sci(h.swarmAt(p, d.reachableCoverage).flops, 2)} FLOP/s`);
line('Crust and mantle dug out', ({ p, d }) => (d.growth.tMantleOut != null ? yr(p, d.growth.tMantleOut) : 'not within 6000 yr'));
line('Core dug out too', ({ p, d }) => (d.growth.tRockOut != null ? yr(p, d.growth.tRockOut) : 'not within 6000 yr'));
line('Share of Mercury dug for the finished swarm', ({ p, E }) => pct(h.minedFor(p, E.mass) / MERCURY.M, 0));
line('Film temperature, finished swarm', ({ p, E }) => `${Math.round(h.closedFilmT(p, E.cap))} K`);
line('Finished swarm: share of the Sun', ({ E }) => `${pct(E.cap, 1)} (${{ rock: 'rock runs out', room: 'closed', climate: 'Earth\'s limit' }[E.binding]})`);
line('Computing, finished swarm', ({ E }) => `${sci(E.flops, 2)} FLOP/s`);
line('Year finished', ({ p, d, E }) => { const t = d.yearsToCoverage(E.cap * 0.995); return yr(p, Number.isFinite(t) ? t : d.growth.tPeak); });
line('Its infrared on Earth (the cap\'s back)', ({ E }) => `${E.forcing.gross.toFixed(2)} W/m²`);
line('Sunlight taken to cancel it', ({ E }) => pct(E.forcing.sunlightCut, 2));
line('Global rainfall', ({ E }) => `−${pct(E.forcing.rainCut, 1)}`);
line('Night sky, finished swarm (Sun 18° down)', ({ E }) => `${E.skyLuxAtCap.toFixed(1)} lux`);
line('For comparison, far side only (±60°)', ({ F }) => `${pct(F.cap, 1)}, ${sci(F.flops, 1)} FLOP/s, −${pct(F.forcing.sunlightCut, 1)} sunlight`);
line('For comparison, open toward Earth (near-uniform)', ({ U }) => `${pct(U.cap, 1)}, ${sci(U.flops, 2)} FLOP/s, −${pct(U.forcing.sunlightCut, 1)} sunlight, −${pct(U.forcing.rainCut, 0)} rain`);
table(['', ...eras.map(e => h.ERAS[e].label)], rows);

const { p, d } = ds.mid;
w('## Central case, year by year');
w('');
table(['Year', 'Sunlight captured', 'FLOP/s', 'Sails', 'Mercury removed', 'Output replacing old sails', 'Sunlight taken to hold Earth\'s temperature', 'Night sky'],
  [20, 50, 60, 70, 80, 100, 120, 150, 164, 250, 400, 700, 1100, 1500].map(t => {
    const a = h.atYear(p, d, t);
    return [String(Math.round(a.calendarYear)), pct(a.f, 3), sci(a.flops, 2), sci(a.nSails, 2), pct(a.mercuryRemoved, 3), pct(a.replacementShare, 0), pct(a.forcing.sunlightCut, 2), `${h.skyLux(p, a.f).toFixed(2)} lux`];
  }));

w('## What sets the ceiling: service life and recycling (central case)');
w('');
table(['Service life', 'Recycled in orbit', 'Ceiling coverage', 'Closed in', 'Lost a year once finished'],
  [[10, 0], [10, 0.9], [15, 0.94], [30, 0.97], [100, 0.99], [300, 0.99], [1000, 0.995]].map(([life, rho]) => {
    const q = { ...p, serviceLife: life, recycleFrac: rho };
    const dq = h.compute(q);
    const t = dq.yearsToCoverage(0.99);
    return [`${life} yr`, pct(rho, rho > 0.99 ? 2 : 0), pct(dq.reachableCoverage, 2), yr(p, t), kg(dq.mass * (1 - rho) / life)];
  }));
w('With the mantle alone (no core) the central case stops at ' + pct(h.compute({ ...p, rockSource: 'mantle' }).reachableCoverage, 1) + '.');
w('');

w('## Concentrating chips costs mass (central case, 1 % coverage)');
w('');
table(['Pod share of chip power', 'Swarm mass per W', 'vs all-sail'], [0, 0.01, 0.03, 0.06, 0.1, 0.15, 0.3].map(q => {
  const s = h.swarmAt({ ...p, podFrac: q, earthPlacement: 'shell' }, 0.01);
  const s0 = h.swarmAt({ ...p, podFrac: 0, earthPlacement: 'shell' }, 0.01);
  return [pct(q, 0), gW(s.kgPerW), `${(s.kgPerW / s0.kgPerW).toFixed(2)}×`];
}));

w('## Hotter chips (central case, 1 % coverage)');
w('');
table(['Chiplet limit', 'Sail orbit', 'Sail mass per W', 'FLOP/s per kg', 'FLOP per joule of sunlight'], [85, 105, 125, 150].map(tj => {
  const s = h.swarmAt({ ...p, tjFilmC: tj, earthPlacement: 'shell' }, 0.01);
  return [`${tj} °C`, `${s.rSail.toFixed(3)} AU`, gW(s.sail.kgPerW), sci(s.sail.flopsPerKg, 2), sci(s.flops / s.intercepted, 2)];
}));

w('## Mercury');
w('');
w(`Rock (crust + mantle) is ${pct(MERCURY.M_SHELL / MERCURY.M, 1)} of Mercury: ${kg(MERCURY.M_SHELL)}. At ${pct(p.yieldDelivered, 0)} yield it can deliver ${kg(MERCURY.M_SHELL * p.yieldDelivered)} of spacecraft.`);
w(`Export is capped at ${sci(d.growth.capToSails * 3.15576e7, 2)} kg/yr by the ${sci(p.mercuryHeatLimit, 2)} W the surface can shed at ${p.heatPerKg} MJ/kg.`);
w('');
w('Where the heat comes from, per kg of rock: digging and crushing ~0.05 MJ; a surface launch to low orbit (3 km/s, 4.5 MJ/kg of kinetic energy) leaves ~0.045 MJ with superconducting launchers at 99 % (0.23 MJ at 95 %, which would make the wall 3× lower). Everything after that happens in orbit: catapults add the rest of the launch and shed their losses to space; reduction, refining and the fabs work there too. Launching the whole way from the surface at 95 % would leave ~1.8 MJ/kg, and refining on the surface tens of MJ/kg.');
w('');
w('What the surface can shed: Mercury\'s 7.5×10¹³ m² radiating at 500 K (ε 0.9) gets rid of only 2.4×10¹⁷ W. Heat pumps at half of Carnot lift the waste heat to radiators at 1,650 K: they radiate 2.8×10¹⁹ W, of which 5×10¹⁸ W is the waste heat and the rest the pumps\' own work, supplied by beamed power. At 2,000 K the same arithmetic gives ~9×10¹⁸ W; refractory radiators cannot go much hotter. The planet paved with radiators is the ceiling; the lever that matters is how few joules per kg stay on it.');
w(`The core (${pct(MERCURY.M_CORE / MERCURY.M, 0)} of the planet, ~6 % silicon) adds ${kg(d.growth.rockCore)} of spacecraft at ${(h.FIXED.rockSi / h.FIXED.coreSi).toFixed(1)}× the heat per kg. The crust and mantle are dug out by ${yr(p, d.growth.tMantleOut)}; the finished swarm (${pct(ds.mid.E.cap, 1)} of the Sun) takes ${pct(h.minedFor(p, ds.mid.E.mass) / MERCURY.M, 0)} of the planet, ${pct(Math.max(0, (h.minedFor(p, ds.mid.E.mass) - MERCURY.M_SHELL) / MERCURY.M_CORE), 0)} of the core (\`docs/closed-swarm.md\`).`);
w('');
w('## Earth');
w('');
w(`Runaway-greenhouse limit: ${EARTH.runawayAbsorbedLimit} W/m² absorbed (today ${EARTH.absorbedSolar.toFixed(0)}). One CO₂ doubling: ${EARTH.co2DoublingForcing} W/m².`);
w('Closed swarm (default): Earth sees only the mirror cap\'s back, 0.56 W/m² (40 layers of aluminium foil, 26 g/m², inner face at ~500 K, ε 0.03 per face; Earth averages 0.40 of the back\'s 1.4 W/m²). Narrowing the window by 0.24 % cancels it. At night the sky within 75–85° of the Sun (by season) is black; the zodiacal light and the planets are gone; the solar wind stops. See `docs/closed-swarm.md`.');
w('');
w('Other layouts: an L1 shade cancels whatever heat the swarm sends, so Earth keeps its mean temperature. What Earth pays is the sunlight the shade takes (1 % per 2.38 W/m²), global rainfall (~0.76 % per W/m² swapped at small swaps, saturating) and a polar residual (+0.23 W/m² per W/m²) that a shade shaped by latitude and season can reduce. With infrared-dark fronts on every sail and no sail within 23° of the Sun–Earth line (so Earth sees no hot back), the near-uniform swarm sends Earth 0.563 W/m² per 1 %; the far-side cloud alone 0.42 at ±60°; an even swarm with glass fronts 2.2–2.7 even with the gap. The night sky is a consequence, not a limit: from Earth the near-uniform swarm is a disc of sunlit fronts out to 72° from the Sun, tau rho S / pi. See `docs/full-swarm.md` and `docs/earth.md`.');
w('');
writeFileSync(out, L.join('\n'));
console.log(`wrote ${out}`);
