// Runs the model and writes NUMBERS.md: every figure the visualizer shows, plus the sweeps behind
// the design choices. Usage: node scripts/report.mjs [out.md]
import { writeFileSync } from 'node:fs';
import * as m from '../src/model/model.js';
import { PHYS, MERCURY, EARTH, REFS, S0 } from '../src/model/constants.js';
import { sci, pct, watts, kg, length, duration } from '../src/util/format.js';

const out = process.argv[2] || 'NUMBERS.md';
const p = m.defaults();
const d = m.compute(p);
const L = [];
const w = (...a) => L.push(a.join(''));
const table = (head, rows) => {
  w('| ', head.join(' | '), ' |');
  w('|', head.map(() => '---').join('|'), '|');
  for (const r of rows) w('| ', r.join(' | '), ' |');
  w('');
};
const K = T => `${Math.round(T)} K`;

w('# The numbers');
w('');
w('Generated by `node scripts/report.mjs` from `src/model/model.js` with the default assumptions. ');
w('The visualizer shows the same numbers, computed by the same code, so changing an assumption in the app changes everything consistently.');
w('');
w('## Default assumptions');
w('');
table(['Parameter', 'Value'], m.PARAMS.filter(s => s.key !== 'year').map(s => [s.label, s.options ? p[s.key] : `${sci(p[s.key], 3)} ${s.unit}`]));

w('## 1. Where a compute swarm has to sit');
w('');
w(`A satellite turns every watt it absorbs into heat: the electricity runs the chips and ends up as heat too. So the panel temperature is set by sunlight and radiation alone. `);
w(`A lone panel at 1 AU runs at ${K(m.sheetTemp(m.flux(1), 0, p))}; at Mercury's orbit ${K(d.tAtMercury)} (${K(d.tAtMercuryClosed)} in a closed shell), far too hot for silicon chips or silicon PV.`);
w('');
w(`A nearly closed swarm is worse than a lone panel: the sunward faces radiate into the far side of the shell, so heat can only leave outward. A closed shell runs ${(m.sheetTemp(m.flux(1), 1, p) / m.sheetTemp(m.flux(1), 0, p)).toFixed(3)}× hotter than a lone panel at the same distance (radiosity model, see \`sheetTemp\`).`);
w('');
w('**Panel temperature T(r, f)**, sun-facing sheet, α = 0.90, ε front 0.85, back 0.90:');
w('');
const fs = [0.001, 0.01, 0.1, 0.5, 0.9, 1];
table(['r (AU)', ...fs.map(f => `f = ${f}`)], [0.387, 0.7, 1, 1.2, 1.4, 1.5, 2].map(r => [r, ...fs.map(f => K(m.sheetTemp(m.flux(r), f, p)))]));
w(`**Placement.** With chips limited to ${K(p.tChipMax)} and a ${p.dTJunction} K rise above the film, the film may reach ${K(d.tSheetMax)}. A finished swarm (coverage ${pct(d.f, 0)}) therefore sits at **${d.rAU.toFixed(2)} AU**, outside Earth's orbit and just inside Mars's (1.52 AU).`);
w('');
table(['Chip limit', 'Film', 'r for 1% swarm', 'r for 10%', 'r for full shell'], [333, 343, 358, 378, 398].map(Tc => {
  const Ts = Tc - p.dTJunction;
  return [`${Tc} K (${Tc - 273} °C)`, K(Ts), ...[0.01, 0.1, 1].map(f => `${m.rForFlux(m.fluxForTemp(Ts, f, p)).toFixed(2)} AU`)];
}));
w(`**The thermodynamic floor.** Whatever the orbit, rejecting L☉ at temperature T needs at least L/(εσT⁴) of radiator: ${sci(m.minRadiatingArea(d.tSheet, p.epsBack, 1))} m² at ${K(d.tSheet)}, ${(m.minRadiatingArea(d.tSheet, p.epsBack, 1) / (4 * Math.PI * PHYS.AU ** 2)).toFixed(2)}× the area of a sphere at 1 AU. Swarm mass scales as T⁻⁴, so the chips' temperature limit, not the choice of orbit, sets how much of Mercury you need.`);
w('');

w('## 2. One satellite');
w('');
table(['Quantity', 'Value'], [
  ['Shape', `hexagon, ${length(2 * d.sat.hexSide)} across corners (${sci(p.satArea)} m²)`],
  ['Mass', kg(d.sat.mass)],
  ['Average thickness (as aluminium)', length(d.sat.equivAlThicknessM)],
  ['Sunlight on it', `${Math.round(d.S)} W/m², ${watts(d.sat.heat)} absorbed`],
  ['PV efficiency at temperature', pct(d.etaPV)],
  ['Electric power to chips', watts(d.sat.elec)],
  ['Compute', `${sci(d.sat.flops)} FLOP/s (${sci(d.sat.h100Equiv)} H100-equivalents)`],
  ['Chip power and pitch', d.chipPitch ? `${p.chipPower} W per chip every ${length(d.chipPitch)}; ${sci(d.chipsPerSat)} chips` : '—'],
]);

w('## 3. The finished swarm');
w('');
table(['Quantity', 'Value'], [
  ['Orbit radius', `${d.rAU.toFixed(3)} AU`],
  ['Panel temperature', K(d.tSheet)],
  ['Satellites', `${sci(d.nSats)} (${sci(d.vsMilkyWayStars)}× the stars in the Milky Way)`],
  ['Total panel area', `${sci(d.satAreaTotal)} m²`],
  ['Power intercepted', `${sci(d.intercepted)} W`],
  ['Electricity', `${sci(d.elecTotal)} W (${sci(d.elecTotal / REFS.worldElectricityW)}× human electricity)`],
  ['Compute', `${sci(d.flopsTotal)} FLOP/s (${sci(d.vsHumanity)}× all AI hardware on Earth, ~${sci(REFS.humanComputeFlops)} FLOP/s)`],
  ['Landauer floor vs. today’s chips', `chips use ${sci(d.landauerGap)}× the kT ln 2 minimum`],
  ['Light time across', duration(d.lightAcross)],
]);

w('## 4. Mercury');
w('');
w(`Mercury is ${pct(MERCURY.M_CORE / MERCURY.M, 1)} iron-silicon core by mass; its crust and mantle together are only ${pct(MERCURY.M_SHELL / MERCURY.M, 1)} (${sci(MERCURY.M_SHELL)} kg), a shell about ${Math.round((MERCURY.R - MERCURY.R_CORE) / 1e3)} km thick over a ${Math.round(MERCURY.R_CORE / 1e3)} km core.`);
w('');
table(['Areal density', 'Swarm mass', 'Mercury dug (incl. propellant)', 'Rock shell used', 'Radius left'], [0.03, 0.06, 0.1, 0.2, 0.3, 1].map(sig => {
  const dd = m.compute({ ...p, arealDensity: sig });
  return [`${sig} kg/m²`, kg(dd.massSwarm), pct(dd.fracMercuryMined, 1), pct(dd.fracShellMined, 0), `${Math.round(m.mercuryRadius(dd.massMined) / 1e3)} km`];
}));
w(`Launch: a mass driver fired at Mercury's perihelion needs ${(d.logistics.vLaunch / 1e3).toFixed(2)} km/s (track ${Math.round(d.logistics.trackLength / 1e3)} km at 100 g), then ${(d.logistics.dvCirc / 1e3).toFixed(2)} km/s from each panel's own ion thruster to circularise at ${d.rAU.toFixed(2)} AU. Gravitational binding energy of Mercury: ${sci(m.bindingEnergy())} J.`);
w('');

w('## 5. Timeline');
w('');
const g = d.growth;
w(`Exponential growth from a ${kg(p.seedMass)} seed, doubling every ${p.doublingYears} yr, until the waste heat of digging and launching (${p.heatPerKg} MJ per kg left on the surface) reaches what Mercury's night side can radiate (${sci(p.mercuryHeatLimit)} W). That happens in year ${g.capped ? g.tCap.toFixed(1) : '—'}; afterwards Mercury exports ${sci(g.rateCap)} kg/s of satellites (${sci(g.rateCap * PHYS.YEAR)} kg a year) and the swarm grows linearly.`);
w('');
const yFor = mass => g.yearsForMass(mass);
table(['Milestone', 'Year'], [
  ['1 billion tonnes (1e12 kg)', yFor(1e12).toFixed(1)],
  ['Coverage 0.0001%', yFor(d.massSwarm * 1e-6).toFixed(1)],
  ['Coverage 1%', yFor(d.massSwarm * 0.01).toFixed(1)],
  ['Coverage 10%', yFor(d.massSwarm * 0.1).toFixed(1)],
  ['Mercury’s rock shell exhausted', d.massMined > MERCURY.M_SHELL ? yFor(MERCURY.M_SHELL / d.logistics.minedPerDelivered).toFixed(1) : 'never'],
  ['Complete', d.growth.yearsToFull.toFixed(1)],
]);
w('Sensitivity of the finish date to the heat limit and areal density:');
w('');
table(['Areal density', ...[1e18, 5e18, 2e19, 1e21].map(h => `limit ${sci(h)} W`), 'no limit'], [0.05, 0.1, 0.2, 0.3].map(sig => [`${sig} kg/m²`, ...[1e18, 5e18, 2e19, 1e21, 1e40].map(h => `${Math.round(m.compute({ ...p, arealDensity: sig, mercuryHeatLimit: h }).growth.yearsToFull).toLocaleString()} yr`)]));

w('## 6. Earth');
w('');
w('Every watt the swarm absorbs is re-radiated as infrared. If the swarm is inside Earth\'s orbit it also dims the Sun; if it is outside, Earth sits inside a glowing shell.');
w('');
table(['Coverage', 'Panel T', 'Extra heat on Earth', '× CO₂ doubling', 'Earth T_eff', 'Night sky'], [1e-4, 1e-3, 0.01, 0.03, 0.1, 0.3, 1].map(f => {
  const T = m.sheetTemp(d.S, f, p);
  const e = m.earthImpact(p, d.rAU, f, T, d.S);
  return [pct(f, 2), K(T), `+${sci(e.forcing, 2)} W/m²`, sci(e.co2Doublings, 2), `${Math.round(e.tEff)} K${e.runaway ? ' (runaway)' : ''}`, `${sci(e.nightLux, 2)} lux`];
}));
w(`References: CO₂ doubling ≈ ${EARTH.co2DoublingForcing} W/m²; runaway greenhouse when Earth absorbs more than ≈${EARTH.runawayAbsorbedLimit} W/m² (Goldblatt et al. 2013), today ${Math.round(EARTH.absorbedSolar)}; full Moon ≈ 0.25 lux, overcast day ≈ 1,000 lux.`);
w('');
w('Interior placement for comparison (same coverage, swarm inside Earth\'s orbit at 0.9 AU, no corridor kept clear):');
w('');
table(['Coverage', 'Extra heat on Earth', 'Sunlight lost'], [0.01, 0.1, 1].map(f => {
  const e = m.earthImpact(p, 0.9, f, m.sheetTemp(m.flux(0.9), f, p), m.flux(0.9));
  return [pct(f, 0), `+${sci(e.forcing, 2)} W/m²`, pct(e.dimming, 0)];
}));

writeFileSync(out, L.join('\n'));
console.log(`wrote ${out} (${L.length} lines)`);
